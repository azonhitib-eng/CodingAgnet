/**
 * Refresh the availability status of an existing adapter.
 *
 * This is a lightweight re-check. It does NOT recreate the adapter.
 */
export async function refreshAdapterStatus(
  adapter: AgentExecutionAdapter,
  options?: {
    openaiConfig?: OpenAIAdapterConfig;
    fetchFn?: FetchFn;
  },
): Promise<AdapterStatus> {
  if (adapter.kind === "stub") {
    return buildAdapterStatus(adapter, "configured_available", {
      label: "Stub (Deterministic / Demo)",
      lastCheckedAt: new Date().toISOString(),
    });
  }

  if (adapter.kind === "echo_test") {
    return buildAdapterStatus(adapter, "configured_available", {
      label: "Echo Test (Deterministic)",
      lastCheckedAt: new Date().toISOString(),
    });
  }

  if (adapter.kind === "openai_compatible" && options?.openaiConfig) {
    const check = await checkOpenAIAvailability(options.openaiConfig, options.fetchFn);
    const availability: AdapterAvailability = check.available
      ? "configured_available"
      : "configured_unavailable";
    return buildAdapterStatus(adapter, availability, {
      modelName: options.openaiConfig.model,
      baseUrl: options.openaiConfig.baseUrl,
      lastCheckedAt: new Date().toISOString(),
      lastError: check.error,
      label: options.openaiConfig.label ?? `OpenAI-compatible (${options.openaiConfig.model})`,
    });
  }

  return buildAdapterStatus(adapter, "unsupported", {
    lastCheckedAt: new Date().toISOString(),
    lastError: `Cannot refresh status for adapter kind: ${adapter.kind}`,
  });
}
